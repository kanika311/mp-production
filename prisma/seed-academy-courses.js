async function main() {
  for (const c of COURSES) {
    await prisma.course.upsert({
      where: { slug: c.slug },
      update: { ...c, isPublished: true, deletedAt: null },
      create: { ...c, isPublished: true },
    });
    console.log(`Seeded course: ${c.slug}`);
  }
  const count = await prisma.course.count({ where: { deletedAt: null } });
  console.log(`\n✅ Done. ${count} courses in DB.`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
